#!/usr/bin/env python3
"""Convert the generated expression sheets into native GPU-sized pixel assets.

This does not draw or invent the portraits. Sources were generated with image_gen.
The original renderings and photograph attribution are retained beside the atlas.
"""
from pathlib import Path
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'assets/portraits'
NAMES = ('pollito', 'hamchow', 'byte', 'magnus', 'hikaru',
         'martin', 'wayne', 'fabian', 'juan', 'filip', 'elani', 'noel', 'oliver',
         'danya', 'kosteniuk', 'ding-liren', 'vishy', 'bok', 'lasker',
         'abdusattorov', 'giri', 'anna-muzychuk', 'irina-krush', 'paul-morphy',
         'vidit', 'aronian', 'judit-polgar', 'hou-yifan', 'ian', 'wesley-so', 'capablanca',
         'leon', 'jill', 'claire', 'chris', 'joel', 'ellie', 'steve', 'alex', 'jensen')
EXPRESSIONS = ('neutral', 'thinking', 'happy', 'frustrated')
# Preserve complete heads while excluding lower clothing that becomes unreadable
# at 32px. Fractional rectangles support any regeneration output dimensions.
BOTTOM_FRACTIONS = {'pollito': .86, 'hamchow': .82, 'byte': .79,
                    'magnus': .90, 'hikaru': .90}


def main():
    atlas = Image.new('RGBA', (256, 1024), (20, 25, 36, 255))
    logical = Image.new('RGBA', (128, len(NAMES) * 32), (20, 25, 36, 255))
    manifest = {'dimensions': [256, 1024], 'rows_per_bank': 32, 'tile': [32, 32],
                'row_order': list(NAMES), 'expression_order': list(EXPRESSIONS),
                'generator': 'OpenAI built-in image_gen',
                'sampling': 'nearest-neighbor; no bilinear filtering',
                'per_character_palette_max': 24, 'rows': []}
    for row, name in enumerate(NAMES):
        if row < 5:
            source = Image.open(DEST / 'source' / (name + '.png')).convert('RGB')
            fraction = BOTTOM_FRACTIONS[name]
            bottom = round(source.height * fraction)
            tiles = []
            for column in range(4):
                left = round(source.width * column / 4)
                right = round(source.width * (column + 1) / 4)
                tiles.append(source.crop((left, 0, right, bottom)).resize((32, 32), Image.Resampling.NEAREST))
        else:
            if row < 13:
                batch, local_row = divmod(row - 5, 4)
                sheet, rows = f'chesscom-{batch}.png', 4
            elif row < 31:
                batch, local_row = divmod(row - 13, 4)
                sheet, rows = f'masters-{batch}.png', (2 if batch == 4 else 4)
            elif row < 39:
                batch, local_row = divmod(row - 31, 4)
                sheet, rows = f'fiction-{batch}.png', 4
            else:
                sheet, rows, local_row = 'jensen.png', 1, 0
            raw = Image.open(DEST / 'source' / sheet).convert('RGBA')
            backdrop = Image.new('RGBA', raw.size, (20, 25, 36, 255))
            backdrop.alpha_composite(raw)
            source = backdrop.convert('RGB')
            fraction = 1.0
            tiles = []
            for column in range(4):
                box = (round(source.width * column / 4), round(source.height * local_row / rows),
                       round(source.width * (column + 1) / 4), round(source.height * (local_row + 1) / rows))
                tiles.append(source.crop(box).resize((32, 32), Image.Resampling.NEAREST))
        # One palette per character so the four expressions remain color-consistent.
        strip = Image.new('RGB', (128, 32), (20, 25, 36))
        for column, tile in enumerate(tiles):
            strip.paste(tile, (column * 32, 0))
        strip = strip.quantize(colors=24, method=Image.Quantize.MEDIANCUT,
                               dither=Image.Dither.NONE).convert('RGBA')
        atlas.paste(strip, ((row // 32) * 128, (row % 32) * 32))
        logical.paste(strip, (0, row * 32))
        manifest['rows'].append({'name': name, 'source_dimensions': list(source.size),
                                 'crop_bottom_fraction': fraction,
                                 'colors': len(strip.getcolors(4096))})
        for column, expression in enumerate(EXPRESSIONS):
            strip.crop((column * 32, 0, column * 32 + 32, 32)).save(
                DEST / (name + '-' + expression + '.png'))
    atlas.save(DEST / 'portraits.png')
    logical.resize((512, len(NAMES) * 128), Image.Resampling.NEAREST).save(DEST / 'preview.png')
    values = [(alpha << 24) | (blue << 16) | (green << 8) | red
              for red, green, blue, alpha in atlas.get_flattened_data()]
    header = ('#pragma once\n#include <cstdint>\n'
              '// Generated by tools/prepare_portraits.py; see docs/PORTRAITS.md for attribution.\n'
              'namespace portraits {\n'
              'inline constexpr int width = 256, height = 1024, tile = 32, characterCount = 40, rowsPerBank = 32;\n'
              'inline constexpr uint32_t atlas[262144] = {\n')
    header += ',\n'.join(','.join(hex(value) for value in values[i:i + 128])
                        for i in range(0, len(values), 128))
    (DEST / 'portraits.hpp').write_text(header + '\n};\n}\n')
    (DEST / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Prepared 40 characters x 4 expressions, atlas256x1024 (1MiB GPU RGBA8)')


if __name__ == '__main__':
    main()
